/**
 * The freeze: a record of exactly what a result is compared against (dataset, thresholds, rubric) and a document
 * generated from the same code, so the documentation cannot drift from what is scored. A test fails if anything here
 * changes without a re-freeze, and a re-freeze after a model has run restarts the two-consecutive-rounds count.
 */
import { createHash } from "node:crypto";

import { ALL_CASES, TEST_SET, caseHash, datasetHash } from "./dataset";
import { CAPABILITIES, RUBRIC, THRESHOLDS } from "./thresholds";

const stable = (v: unknown): string =>
  Array.isArray(v) ? `[${v.map(stable).join(",")}]` : v && typeof v === "object" ? `{${Object.keys(v as object).sort().map((k) => `${JSON.stringify(k)}:${stable((v as Record<string, unknown>)[k])}`).join(",")}}` : JSON.stringify(v);

export const standardsHash = () => createHash("sha256").update(stable({ THRESHOLDS, CAPABILITIES, RUBRIC })).digest("hex");

export interface FreezeRecord {
  version: 1;
  frozenOn: string;
  datasetHash: string;
  standardsHash: string;
  cases: { id: string; set: string; hash: string }[];
  /** Every change made after the first freeze, with the reason. Empty at the first freeze. */
  changeLog: { date: string; what: string; why: string }[];
}

export const FROZEN_ON = "2026-11-26";

export function freezeRecord(changeLog: FreezeRecord["changeLog"] = []): FreezeRecord {
  return { version: 1, frozenOn: FROZEN_ON, datasetHash: datasetHash(), standardsHash: standardsHash(), cases: ALL_CASES.map((c) => ({ id: c.id, set: c.set, hash: caseHash(c) })), changeLog };
}

const T = THRESHOLDS;
const row = (...cells: (string | number)[]) => `| ${cells.join(" | ")} |`;

